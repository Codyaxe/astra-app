export const DRIFT_SECONDS = [60, 90, 120] as const;
export interface Star {
  source: readonly [number, number, number, number];
  x: number; y: number; depth: number; twinkleSeconds: number; offset: number;
}
export function createStars(mobile: boolean, random = Math.random): Star[] {
  return STAR_SOURCES.filter((_, index) => !mobile || index % 2 === 0).map((source, index) => ({
    source, x: source[0] / 1440, y: source[1] / 750, depth: index % 3,
    twinkleSeconds: 4 + random() * 4, offset: random() * Math.PI * 2,
  }));
}
const wrap = (value: number) => ((value % 1) + 1) % 1;
export function starFrame(star: Star, seconds: number, width: number, height: number, reducedMotion = false) {
  const progress = reducedMotion ? 0 : seconds / DRIFT_SECONDS[star.depth];
  return {
    x: wrap(star.x + progress) * width,
    y: wrap(star.y - progress) * height,
    opacity: reducedMotion ? .6 : .6 + .3 * Math.sin(seconds * Math.PI * 2 / star.twinkleSeconds + star.offset),
  };
}
